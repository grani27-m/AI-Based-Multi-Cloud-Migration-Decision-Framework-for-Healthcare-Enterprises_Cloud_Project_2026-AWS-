SUMMARISE = ["dataset/raw/ripe_atlas/", "dataset/raw/physionet_bidmc/", "standalone_demos/charles/", "standalone_demos/tanmay/",
             "standalone_demos/rani/", "results/model/experiments/", "docs/archive/", "docs/reference/", "docs/research/",
             "frontend/public/", "results/screenshots/", "results/tests/standalone/"]


def owner(f: str) -> tuple[str, str]:
    for prefix, o, w in RULES:
        if f.startswith(prefix):
            return o, w
    return ALL, "E"


def main() -> int:
    git = ["git", "-C", str(ROOT), "ls-files"]
    files = set(subprocess.run(git, capture_output=True, text=True, check=True).stdout.split())
    files |= set(subprocess.run(git + ["--others", "--exclude-standard"], capture_output=True, text=True, check=True).stdout.split())
    out = ["# File ownership matrix", "",
           "Every repository file mapped to its owner and workstream (A–E, see `docs/WORKSTREAM_MAPPING.md`). Generated by",
           "`python -m scripts.generate_ownership_matrix`; large data folders and the standalone packages are summarised per",
           "folder (package files are byte-identical copies, see each `EXPORTED_FILES.json`). Owner = the member who must be",
           "able to run and explain the file; how this AI-assisted integration was produced: `reports/TEAM_CONTRIBUTIONS.md`.",
           "", "| File | Owner | WS |", "|---|---|---|"]
    summ: collections.Counter = collections.Counter()
    meta, totals = {}, collections.Counter()
    for f in sorted(files):
        o, w = owner(f)
        totals[o.split(" ")[0]] += 1
        big = next((b for b in SUMMARISE if f.startswith(b)), None)
        if big:
            summ[big] += 1
            meta[big] = (o, w)
        else:
            out.append(f"| `{f}` | {o} | {w} |")
    out += ["", "## Folders summarised", "", "| Folder | Files | Owner | WS |", "|---|---|---|---|"]
    out += [f"| `{k}` | {n} | {meta[k][0]} | {meta[k][1]} |" for k, n in sorted(summ.items())]
    out += ["", "Totals by first-named owner: " + ", ".join(f"{k} {v}" for k, v in sorted(totals.items())) + " files."]
    (ROOT / "docs" / "FILE_OWNERSHIP_MATRIX.md").write_text("\n".join(out) + "\n")
    print(f"{len(files)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
